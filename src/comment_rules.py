def get_level_by_score(score: float) -> str:
    """根据分数获取评价等级"""
    if score >= 90:
        return "优秀"
    elif score >= 80:
        return "良好"
    elif score >= 70:
        return "中等"
    else:
        return "待提高"


# 连接词/过渡语，增加评语多样性
CONNECTORS = {
    "具体表现": [
        "",
        "具体而言，",
        "从内容来看，",
        "在具体表现上，",
        "就实训过程而言，",
    ],
    "改进建议": [
        "",
        "总体来说，",
        "综合来看，",
        "针对后续发展，",
        "为进一步提升，",
    ],
}


def generate_comment(score: float, used_combinations: set = None) -> Tuple[str, Tuple[int, int, int]]:
    """
    根据分数生成评语
    
    Args:
        score: 学生分数
        used_combinations: 已使用的组合索引集合，用于避免重复
        
    Returns:
        (评语文本, 组合索引元组)
    """
    if used_combinations is None:
        used_combinations = set()
    
    level = get_level_by_score(score)
    pool = COMMENT_POOL[level]
    
    # 获取各语义池的长度
    len_overall = len(pool["总体评价"])
    len_detail = len(pool["具体表现"])
    len_suggestion = len(pool["改进建议"])
    
    # 计算所有可能的组合数
    total_combinations = len_overall * len_detail * len_suggestion
    
    # 尝试找到未使用的组合
    max_attempts = total_combinations
    for _ in range(max_attempts):
        idx_overall = random.randint(0, len_overall - 1)
        idx_detail = random.randint(0, len_detail - 1)
        idx_suggestion = random.randint(0, len_suggestion - 1)
        
        combination = (idx_overall, idx_detail, idx_suggestion)
        
        # 如果这个组合未被使用，或者所有组合都已使用
        if combination not in used_combinations or len(used_combinations) >= total_combinations:
            break
    
    # 随机选择连接词
    conn_detail = random.choice(CONNECTORS["具体表现"])
    conn_suggestion = random.choice(CONNECTORS["改进建议"])
    
    # 组合评语（添加连接词增加多样性）
    comment = (
        pool["总体评价"][idx_overall] + 
        conn_detail + pool["具体表现"][idx_detail] + 
        conn_suggestion + pool["改进建议"][idx_suggestion]
    )
    
    return comment, combination


def get_all_levels() -> List[str]:
    """获取所有评价等级"""
    return list(COMMENT_POOL.keys())
